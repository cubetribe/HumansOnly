import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const rootDir = resolve(process.cwd());
const packageJsonPath = resolve(rootDir, "package.json");
const versionFilePath = resolve(rootDir, "src/version.ts");
const plainVersionFilePath = resolve(rootDir, "version");

const packageJson = JSON.parse(readFileSync(packageJsonPath, "utf8"));
const version = packageJson.version;

if (!version || typeof version !== "string") {
    throw new Error("Could not read version from package.json.");
}

const content = `// This file is generated by scripts/sync-version-file.mjs\nexport const APP_VERSION = "${version}";\n`;

writeFileSync(versionFilePath, content, "utf8");
writeFileSync(plainVersionFilePath, `${version}\n`, "utf8");
console.log(`Synced app version file to ${version}`);
